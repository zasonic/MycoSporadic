def _append_only_guards() -> None:
    """The ledger is immutable at the database level, not by convention."""
    bind = op.get_bind()
    dialect = bind.dialect.name
    for table in APPEND_ONLY:
        if dialect == "sqlite":
            for verb in ("UPDATE", "DELETE"):
                op.execute(
                    f"CREATE TRIGGER IF NOT EXISTS {table}_no_{verb.lower()} "
                    f"BEFORE {verb} ON {table} BEGIN "
                    f"SELECT RAISE(ABORT, '{table} is append-only'); END;"
                )
        elif dialect == "postgresql":
            op.execute(
                "CREATE OR REPLACE FUNCTION mycoloop_append_only() RETURNS trigger AS $$ "
                "BEGIN RAISE EXCEPTION '% is append-only', TG_TABLE_NAME; END; $$ LANGUAGE plpgsql;"
            )
            op.execute(f"DROP TRIGGER IF EXISTS {table}_append_only ON {table};")
            op.execute(
                f"CREATE TRIGGER {table}_append_only BEFORE UPDATE OR DELETE ON {table} "
                "FOR EACH ROW EXECUTE FUNCTION mycoloop_append_only();"
            )


def _timescale() -> None:
    """PostgreSQL only: telemetry_clean becomes a hypertable + 5-minute aggregate."""
    bind = op.get_bind()
    if bind.dialect.name != "postgresql":
        return
    try:
        op.execute("CREATE EXTENSION IF NOT EXISTS timescaledb")
        op.execute("ALTER TABLE telemetry_clean DROP CONSTRAINT IF EXISTS telemetry_clean_pkey")
        op.execute("ALTER TABLE telemetry_clean ADD PRIMARY KEY (id, ts)")
        op.execute("SELECT create_hypertable('telemetry_clean', 'ts', if_not_exists => TRUE, migrate_data => TRUE)")
        op.execute(
            "CREATE MATERIALIZED VIEW IF NOT EXISTS telemetry_5min "
            "WITH (timescaledb.continuous) AS "
            "SELECT device_id, time_bucket('5 minutes', ts) AS bucket, "
            "avg(temperature_c) AS avg_temp_c, avg(humidity_pct) AS avg_humidity_pct, "
            "avg(co2_ppm) AS avg_co2_ppm, count(*) AS samples "
            "FROM telemetry_clean GROUP BY device_id, bucket WITH NO DATA"
        )
    except Exception as exc:  # pragma: no cover - depends on the server build
        print(f"[mycoloop] Timescale setup skipped: {exc}")


